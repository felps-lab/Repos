"""Generate pt-BR narration with Kokoro (local, offline) and word-level captions.

Usage: python scripts/voiceover.py <kokoro.onnx> <voices.bin>

For every video in scripts.json this writes:
  public/<video>/voice.wav          - the full narration track
  src/generated/<video>.ts          - scene boundaries + Caption[] (word timings)

Each clause (split on punctuation) is synthesized separately, trimmed, and
joined with controlled pauses, so caption timing is anchored at every clause.
Inside a clause, word timings are distributed by letter count.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

ROOT = Path(__file__).resolve().parent.parent
LEAD_IN = 0.45  # seconds of silence before the first word
SCENE_GAP = 0.32
PAUSE = {",": 0.14, ":": 0.2, ".": 0.3, "?": 0.32, "!": 0.3}
TAIL = 2.2  # music-only outro after the last word


def clauses(text: str):
    parts = re.findall(r"[^,.:?!]+[,.:?!]*", text)
    return [p.strip() for p in parts if p.strip()]


def trim(audio: np.ndarray, sr: int, thresh=0.012):
    idx = np.where(np.abs(audio) > thresh)[0]
    if len(idx) == 0:
        return audio
    pad = int(0.03 * sr)
    return audio[max(0, idx[0] - pad): min(len(audio), idx[-1] + pad)]


def word_weight(w: str):
    return len(re.sub(r"[^\wÀ-ÿ]", "", w)) + 1.5


def main():
    model, voices = sys.argv[1], sys.argv[2]
    kokoro = Kokoro(model, voices)
    config = json.loads((ROOT / "scripts" / "scripts.json").read_text())
    (ROOT / "src" / "generated").mkdir(parents=True, exist_ok=True)

    for video, cfg in config.items():
        sr = 24000
        chunks = [np.zeros(int(LEAD_IN * sr), dtype=np.float32)]
        t = LEAD_IN
        captions, scenes = [], []
        for scene in cfg["scenes"]:
            shown = clauses(scene["text"])
            spoken = clauses(scene.get("tts", scene["text"]))
            assert len(shown) == len(spoken), (video, scene["id"])
            scene_start = t
            for i, (c_show, c_tts) in enumerate(zip(shown, spoken)):
                audio, sr = kokoro.create(c_tts, voice=cfg["voice"], speed=cfg["speed"], lang="pt-br")
                audio = trim(audio.astype(np.float32), sr)
                dur = len(audio) / sr
                words = c_show.split()
                weights = [word_weight(w) for w in words]
                total = sum(weights)
                wt = t
                for j, (w, wgt) in enumerate(zip(words, weights)):
                    d = dur * wgt / total
                    captions.append({
                        "text": (" " if captions else "") + w,
                        "startMs": round(wt * 1000),
                        "endMs": round((wt + d) * 1000),
                        "timestampMs": round((wt + d / 2) * 1000),
                        "confidence": None,
                    })
                    wt += d
                chunks.append(audio)
                t += dur
                last = i == len(shown) - 1
                gap = SCENE_GAP if last else PAUSE.get(c_show[-1], 0.1)
                chunks.append(np.zeros(int(gap * sr), dtype=np.float32))
                t += gap
            captions[-1]["pageBreakAfter"] = True
            scenes.append({"id": scene["id"], "startMs": round(scene_start * 1000), "endMs": round(t * 1000)})

        chunks.append(np.zeros(int(TAIL * sr), dtype=np.float32))
        t += TAIL
        scenes[-1]["endMs"] = round(t * 1000)
        voice = np.concatenate(chunks)
        voice = voice / max(1e-6, np.abs(voice).max()) * 0.9
        out_dir = ROOT / "public" / video
        out_dir.mkdir(parents=True, exist_ok=True)
        raw = out_dir / "voice_raw.wav"
        sf.write(raw, voice, sr)
        # Light compression + loudness normalization to -15 LUFS (social video level).
        subprocess.run(
            ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(raw), "-af",
             "highpass=f=70,acompressor=threshold=-20dB:ratio=3:attack=5:release=80,loudnorm=I=-15:TP=-1.5:LRA=7",
             "-ar", "44100", str(out_dir / "voice.wav")],
            check=True,
        )
        raw.unlink()

        data = {"totalMs": round(t * 1000), "scenes": scenes, "captions": captions}
        ts = (
            "// Generated by scripts/voiceover.py - do not edit by hand.\n"
            "import type {Caption} from '@remotion/captions';\n\n"
            f"export const {video}Voice: {{totalMs: number; scenes: {{id: string; startMs: number; endMs: number}}[]; captions: Caption[]}} = "
            + json.dumps(data, ensure_ascii=False, indent=1).replace("null", "null")
            + ";\n"
        )
        (ROOT / "src" / "generated" / f"{video}.ts").write_text(ts)
        print(f"{video}: {t:.1f}s, {len(captions)} words")


if __name__ == "__main__":
    main()
